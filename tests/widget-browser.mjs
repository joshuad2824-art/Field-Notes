import assert from 'node:assert/strict'
import {execSync} from 'node:child_process'
import {mkdirSync} from 'node:fs'
const {chromium}=await import(`${execSync('npm root -g',{encoding:'utf8'}).trim()}/playwright/index.mjs`)
const BASE=process.env.BASE||'http://127.0.0.1:5188'
if(!['127.0.0.1','localhost'].includes(new URL(BASE).hostname))throw Error('Local fixtures only')
mkdirSync('work/check-results/widgets',{recursive:true})
const browser=await chromium.launch()
try {
 for(const width of [390,820]) {
  const context=await browser.newContext({viewport:{width,height:900}})
  const outside=[]
  await context.route('**/*',r=>{if(new URL(r.request().url()).origin===BASE)return r.continue();outside.push(r.request().url());return r.abort()})
  const p=await context.newPage(),errors=[];p.on('pageerror',e=>errors.push(e.message))
  await p.goto(BASE+'/tests/redesign-check.html');await p.getByRole('button',{name:'Load redesign fixtures'}).click();await p.getByText('Fixtures ready').waitFor()
  await p.goto(BASE+'/quick-note?source=scriptable')
  await p.getByRole('heading',{name:'Connect this browser',exact:true}).waitFor()
  assert.equal(await p.getByRole('textbox',{name:'Quick note',exact:true}).count(),0,'widget cannot silently start a separate archive')
  await p.getByRole('button',{name:'Open Sync settings',exact:true}).click()
  await p.getByRole('heading',{name:'Sync',exact:true}).waitFor()
  const initial=await p.evaluate(async()=>{const {db}=await import('/src/lib/db.ts');return db.pages.toArray()})
  await p.goto(BASE+'/quick-note');await p.getByRole('textbox',{name:'Quick note',exact:true}).waitFor()
  assert.ok(p.url().endsWith('/overview'),'capture route replaced with Today')
  await p.getByRole('textbox',{name:'Quick note',exact:true}).fill('Fictional widget draft\nKeep this thought.')
  await p.getByRole('button',{name:'Done',exact:true}).click()
  await p.goto(BASE+'/quick-note');assert.equal(await p.getByRole('textbox',{name:'Quick note',exact:true}).inputValue(),'Fictional widget draft\nKeep this thought.')
  await p.getByRole('radio',{name:'Church',exact:true}).click();await p.getByRole('button',{name:'Done',exact:true}).click()
  await p.reload()
  const after=await p.evaluate(async()=>{const {db}=await import('/src/lib/db.ts');return db.pages.toArray()})
  assert.equal(after.length,initial.length+1)
  for(const original of initial) assert.deepEqual(after.find(row=>row.id===original.id),original,'existing page preserved')
  assert.equal(after.filter(row=>row.body==='Fictional widget draft\nKeep this thought.').length,1)
  await p.goto(BASE+'/quick-note');assert.equal(await p.getByRole('textbox',{name:'Quick note',exact:true}).inputValue(),'');await p.getByRole('button',{name:'Done',exact:true}).click()
  await p.goto(BASE+'/calendar/2026-11');await p.getByRole('button',{name:'November 2026 — open the day agenda',exact:true}).waitFor()
  await p.goto(BASE+'/weather');await p.getByRole('heading',{name:'Weather',exact:true}).waitFor()
  assert.ok(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'weather fits')
  await p.screenshot({path:`work/check-results/widgets/weather-${width}.png`})
  await p.goto(BASE+'/settings');await p.getByRole('heading',{name:'Home Screen widgets'}).waitFor()
  assert.equal(await p.getByRole('button',{name:'Connect calendar',exact:true}).count(),0,'unpaired device cannot activate')
  assert.equal(outside.some(url=>url.includes('/rpc/widget_')),false,'no calendar connection or credential created by rendering')
  await p.locator('#settings-widgets').scrollIntoViewIfNeeded()
  await p.screenshot({path:`work/check-results/widgets/settings-${width}.png`})
  const calls=[]
  await p.route('https://fictional.supabase.co/rest/v1/rpc/*',async route=>{
   calls.push({url:route.request().url(),body:route.request().postDataJSON()})
   await route.fulfill({status:200,contentType:'application/json',body:'null'})
  })
  await p.evaluate(async()=>{const {setVault}=await import('/src/sync/vault.ts');const {vaultIdFor}=await import('/src/sync/pairing.ts');const key='A'.repeat(43);setVault({url:'https://fictional.supabase.co',anonKey:'fictional-public-key-for-tests',key,id:await vaultIdFor(key)})})
  await p.goto(BASE+'/quick-note?source=scriptable')
  await p.getByRole('textbox',{name:'Quick note',exact:true}).waitFor()
  await p.getByRole('button',{name:'Done',exact:true}).click()
  await p.goto(BASE+'/settings')
  await p.getByRole('checkbox',{name:/Allow Scriptable/}).check()
  await p.getByRole('button',{name:'Connect calendar',exact:true}).click()
  await p.getByText('Calendar connected. Keep the setup code private.').waitFor()
  const code=JSON.parse(await p.getByRole('textbox',{name:'Private Scriptable setup code'}).inputValue())
  assert.deepEqual(Object.keys(code).sort(),['version','url','publicKey','token'].sort())
  assert.equal(JSON.stringify(code).includes('A'.repeat(43)),false,'no archive key exported')
  assert.equal(calls.filter(c=>c.body.p_create===true).length,1)
  const payload=calls.find(c=>c.body.p_create===true).body
  assert.ok(payload.p_hash&&payload.p_snapshot);assert.equal('token' in payload,false,'server receives a token hash')
  assert.ok(!JSON.stringify(payload).includes('Fictional widget draft'))
  await p.getByRole('button',{name:'Hide setup code',exact:true}).click()
  await p.getByRole('button',{name:'Revoke calendar widget',exact:true}).click()
  await p.getByText('Calendar widget access revoked.').waitFor()
  assert.equal(await p.getByRole('textbox',{name:'Private Scriptable setup code'}).count(),0)
  assert.equal(await p.evaluate(()=>localStorage.getItem('field-notes.widget')),null)
  await p.waitForTimeout(1800)
  assert.equal(calls.filter(c=>c.body.p_create===true).length,1,'no automatic recreation after revoke')
  assert.equal(calls.filter(c=>c.url.endsWith('/widget_revoke')).length,1)
  assert.deepEqual(errors,[])
  await context.close()
 }
 console.log('PASS widget browser 390/820px: deep links, existing draft retained, notebook filing exactly once, all original pages unchanged, blank reopening, calendar/weather destinations, no automatic credential creation, no page errors.')
} finally {await browser.close()}
